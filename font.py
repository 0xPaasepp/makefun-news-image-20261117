def normalize(text):
    """Map fancy punctuation to glyphs we have; drop anything unknown."""
    repl = {'—': '-', '–': '-', '“': '"', '”': '"', '‘': "'",
            '’': "'", '…': '.', '°': 'o', '×': 'x'}
    out = []
    for ch in text:
        if ch in repl:
            out.append(repl[ch])
        elif ch in FONT:
            out.append(ch)
        # unknown chars are dropped silently
    return ''.join(out)
