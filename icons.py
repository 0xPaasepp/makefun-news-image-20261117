def draw_icon(cv, x, y, name, cell=2):
    """Draw one 12x12 icon at (x, y) top-left, 2px per cell = 24x24 px."""
    grid = ICONS.get(name)
    if not grid:
        return
    for r, row in enumerate(grid):
        for c, ch in enumerate(row):
            color = COLORS.get(ch)
            if color is None:
                continue
            for dy in range(cell):
                for dx in range(cell):
                    cv.px(x + c * cell + dx, y + r * cell + dy, color)
